#!/usr/bin/env bash
# Assembles a docfx page from BenchmarkDotNet's GitHub-markdown exports.
#
# Usage: build-benchmark-doc.sh <artifacts-dir> <output-file>
#
# <artifacts-dir> is the --artifacts path passed to the benchmark run; the
# exports live in <artifacts-dir>/results/*-report-github.md.
set -euo pipefail

artifacts="${1:?artifacts dir required}"
output="${2:?output file required}"

results="${artifacts}/results"
shopt -s nullglob
reports=("${results}"/*-report-github.md)
if [ ${#reports[@]} -eq 0 ]; then
    echo "no *-report-github.md found in ${results}" >&2
    exit 1
fi

mkdir -p "$(dirname "${output}")"

{
    echo "# JSON Serializer Benchmarks (CI)"
    echo
    echo "> Generated by the \`json-benchmarks\` workflow. Do not edit by hand."
    echo
    echo "| | |"
    echo "| --- | --- |"
    echo "| Generated | ${GENERATED_AT:-$(date -u +'%Y-%m-%d %H:%M:%S UTC')} |"
    echo "| Commit | \`${GITHUB_SHA:-local}\` |"
    echo "| Runner | ${RUNNER_OS:-local} |"
    echo "| Job | ${BDN_JOB:-short} |"
    echo
    echo "GitHub-hosted runners are shared virtual machines. Treat these numbers as"
    echo "relative rankings, not as reproducible absolute timings — see the per-project"
    echo "\`README.MD\` for results measured on dedicated hardware."
    echo

    for report in "${reports[@]}"; do
        # Benchmarks.Serializers.Json.Benchmarks.SerializationBenchmark-report-github.md
        #   -> SerializationBenchmark
        name="$(basename "${report}" -report-github.md)"
        name="${name##*.}"
        echo "## ${name}"
        echo
        cat "${report}"
        echo
    done
} > "${output}"

echo "wrote ${output} from ${#reports[@]} report(s)"
